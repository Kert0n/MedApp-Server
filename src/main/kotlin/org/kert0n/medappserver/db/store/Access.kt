// Правила обращения к хранилищам — в одном месте на весь пакет `db/store`.
//
// Хранилище — единственное, что умеет достать строку. Значит и вопрос «а вправе ли вызывающий её
// видеть» решается здесь, а не в слое выше. Правил три, и они разной силы.
//
// 1. ЧТЕНИЕ ПРИНИМАЕТ ВЫЗЫВАЮЩЕГО, И СКОУП НАКЛАДЫВАЕТ ЗАПРОС.
//    Публичное чтение обязано назвать `userId`, а предикат членства добавляет помощник запроса
//    (`drugsAccessibleTo`, `withCaller`, `visibleTo`) — не само чтение. Дописывать предикат в
//    каждом чтении означало бы помнить о нём в каждом чтении; забыть один раз — значит выпустить
//    наружу чужую версию вместе с фактом существования пачки.
//    Чужого и несуществующего хранилище не различает: и то и другое — `null`, иначе код ответа
//    выдавал бы существование чужой строки.
//
// 2. КОМАНДА ПРИНИМАЕТ АГРЕГАТ, И ЭТИМ ДОСТУП ДОКАЗАН.
//    У публичной записи предиката членства нет, и это не пропуск: аргументом идёт `Drug`,
//    `MedKit`, `Reservation` — то, что вызывающий уже прочитал скоуплено. Второй предикат был бы
//    второй копией того же правила и стоил бы лишнего соединения на каждой записи.
//    Идентификатор в записи означал бы «поверь, что я проверил», а проверял его никто.
//
// 3. ОБЕЩАНИЕ ДАЁТ ДВЕРЬ, А НЕ КОМНАТА.
//    Правила 1 и 2 — про публичную поверхность хранилища. Приватные помощники под разделом
//    «внутреннее» работают уже внутри доказанной команды и берут то, что из агрегата достали:
//    идентификатор, дельту, набор участников. Это не исключение из правила, а его область
//    действия — но заметить разницу можно только по разделу, поэтому разделы и подписаны.
//
// ЧЕГО ЗДЕСЬ НЕТ. Ни одно из трёх правил не проверяется тестом: `CommandsTakeAggregatesTest`
// опознаёт команды по `@Transactional(propagation = MANDATORY)` и в этот пакет не заглядывает
// вовсе — приватный помощник с идентификатором проезжает под разделом про агрегаты незамеченным.
// Пока это держится комментарием и ревью. Настоящие решения — в issue:
//
//   #103 — база не отдаёт чужое сама (RLS), и тогда правило 1 перестаёт зависеть от памяти;
//   #104 — у агрегата две двери, и тогда объект нельзя собрать мимо хранилища.

package org.kert0n.medappserver.db.store

import kotlin.uuid.Uuid
import org.jetbrains.exposed.v1.core.Column
import org.jetbrains.exposed.v1.core.Op
import org.jetbrains.exposed.v1.core.eq
import org.jetbrains.exposed.v1.core.inSubQuery
import org.jetbrains.exposed.v1.jdbc.select
import org.kert0n.medappserver.db.tables.MedKitMemberships

/**
 * Что значит «доступно вызывающему» — в одном месте на все хранилища.
 *
 * Доступ даёт членство в аптечке, и любая строка, у которой есть аптечка, проверяется
 * одинаково — упаковка, бронь, что угодно дальше. Написать это условие второй раз значило бы
 * завести второе место, где его можно поправить наполовину.
 */
internal fun Column<Uuid>.inMedKitsOf(userId: Uuid): Op<Boolean> =
    this inSubQuery MedKitMemberships
        .select(MedKitMemberships.medKitId)
        .where { MedKitMemberships.userId eq userId }
