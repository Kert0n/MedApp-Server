package org.kert0n.medappserver.domain

import kotlin.uuid.Uuid

/**
 * Выданное приглашение в аптечку.
 *
 * Хранит идентификатор, а не прочитанную аптечку: снимок чтения ничего не удостоверяет, а
 * приглашение и не должно ничего удостоверять само по себе. Право проверяется в момент
 * вступления — под исключительной блокировкой корня, и правами пригласившего.
 *
 * Помнит выдавшего, и это не справка: вступление проверяет доступ **его** правами, потому что
 * приглашённого в аптечке ещё нет. Отсюда следствие, которое стоит знать: пригласивший вышел —
 * приглашение перестало работать. Оно выдано на его правах, а не само по себе.
 */
class Invitation(val medKitId: Uuid, val invitedBy: Uuid)
