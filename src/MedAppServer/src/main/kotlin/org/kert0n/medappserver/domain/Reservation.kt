package org.kert0n.medappserver.domain

import java.util.UUID

/**
 * Бронь — заявка человека на часть упаковки: «эти двадцать таблеток мои».
 *
 * Самостоятельный корень агрегата со своей жизнью. Раньше это был «план лечения» внутри
 * препарата, и он не сходился ни с чем, потому что не было решено, что он такое в физическом
 * мире. Бронь — вещь понятная: она принадлежит своему владельцу, он один её заводит, меняет и
 * отменяет.
 *
 * **Бронь может превышать остаток упаковки, и это нормальное состояние.** В пачке тридцать
 * таблеток, забронировано сорок — система об этом не переживает: что с этим делать, решает
 * владелец брони. Сервер не чинит планы клиента, и именно попытка чинить их за него раньше
 * приводила к пропорциональным пересчётам, которых никто не просил.
 *
 * Идентичность — пара «человек и упаковка»: одна бронь на пачку от одного человека. Ссылка на
 * упаковку по идентификатору, а не объектом: это другой агрегат.
 *
 * Бронь не переживает уничтожения упаковки — бронь на выброшенную пачку бессмысленна. Это
 * правило целостности данных, а не владения: его держит внешний ключ с каскадом, а не
 * коллекция внутри упаковки.
 */
data class Reservation(
    val userId: UUID,
    val drugId: UUID,
    val amount: Quantity
) {

    init {
        if (!amount.isPositive) throw InvalidQuantity()
    }

    /**
     * Новый размер брони.
     *
     * Ограничения сверху нет: превысить остаток упаковки бронью можно. Ноль — не размер
     * брони, а её отмена, и выражается она удалением.
     */
    fun changeTo(newAmount: Quantity): Reservation {
        if (!newAmount.isPositive) throw InvalidQuantity()
        if (newAmount.unit != amount.unit) throw QuantityUnitMismatch()
        return copy(amount = newAmount)
    }
}
