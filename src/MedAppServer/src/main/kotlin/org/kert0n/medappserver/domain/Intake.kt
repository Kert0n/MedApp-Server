package org.kert0n.medappserver.domain

import java.util.UUID

/**
 * Запись о выполненной синхронизации: что клиент попросил сделать с этой пачкой.
 *
 * Существует ради одного вопроса — «этот запрос уже выполнялся?». Клиент шлёт суммы, а не
 * поток событий, поэтому повтор после обрыва связи обязан не списать второй раз, и отличить
 * повтор от новой команды можно только по тому, что клиент сам её пометил.
 *
 * Идентичность — `id`, его выбирает клиент. Сравнение при этом **структурное**, и это не
 * противоречие: запись неизменяема и после появления не меняется никогда, так что «тот же
 * идентификатор» и «то же содержимое» либо совпадают, либо запрос противоречив. Отпечатка
 * строкой здесь нет намеренно: сравниваются поля, а не их печатное представление, — иначе
 * `20.0` и `20.000000` считались бы разными запросами.
 *
 * Величины хранятся целиком, вместе с единицей: сравнивать «двадцать» с «двадцатью» без неё
 * значит однажды принять миллилитры за таблетки.
 */
data class Intake(
    val id: UUID,
    val drugId: UUID,
    val userId: UUID,
    /** `null` — приёма в запросе не было, менялась только бронь. */
    val consumed: Quantity? = null,
    /** `null` — бронь в запросе не упоминалась. */
    val reservedTo: Quantity? = null
) {

    init {
        if (consumed == null && reservedTo == null) throw EmptySync()
        if (consumed != null && !consumed.isPositive) throw InvalidQuantity()
        if (reservedTo != null && !reservedTo.isPositive) throw InvalidQuantity()
    }

    /** Повтор — та же запись целиком. Тот же идентификатор с другим содержимым запросом не является. */
    fun isRepeatOf(previous: Intake): Boolean = this == previous
}

