package org.kert0n.medappserver.services.application

/**
 * Предусловие команды: клиент предъявляет версию того, что видел.
 *
 * Предъявленное отсюда едет в саму запись и становится предикатом `UPDATE`: сверять его
 * заранее незачем, а забыть сверку — нельзя, потому что записать без версии не собирается.
 *
 * Здесь остаётся единственное, чего предикат сделать не может: отличить **не предъявлено** от
 * предъявленного. Команда без версии — это команда вслепую, и отвечать на неё 412 неверно:
 * предусловия не было, а не не выполнилось.
 */
class PreconditionRequired : RuntimeException("The command must state the version it acts on")

/** Версия, которую команда обязана была предъявить. */
fun statedVersion(version: Long?): Long = version ?: throw PreconditionRequired()
