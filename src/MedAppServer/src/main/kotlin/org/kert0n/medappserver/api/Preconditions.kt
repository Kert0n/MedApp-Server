package org.kert0n.medappserver.api

/**
 * Предусловие команды: клиент предъявляет версию того, что видел.
 *
 * Живёт рядом с формами запроса, а не в прикладном слое: «на что ты смотрел, когда решал» —
 * условие протокола, а не правило предметной области. Ниже про него не рассуждают вовсе:
 * предъявленное едет в саму запись и становится предикатом `UPDATE`.
 *
 * Отсюда и единственное, что здесь есть. Отличить **не предъявлено** от предъявленного
 * предикат не может: команда без версии до записи просто не доходит. Отвечать на неё 412
 * неверно — предусловия не было, а не не выполнилось.
 */
class PreconditionRequired : RuntimeException("The command must state the version it acts on")

/**
 * Версия, которую команда обязана была предъявить.
 *
 * Разворачивается там, где запрос становится командой: в теле — при сборке команды, в
 * параметре — при входе в фасад. Ниже нулевых версий не бывает.
 */
fun statedVersion(version: Long?): Long = version ?: throw PreconditionRequired()
