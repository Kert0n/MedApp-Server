package org.kert0n.medappserver.domain

import java.util.UUID

/**
 * Выданное приглашение в аптечку.
 *
 * Принимает настоящую аптечку, а не её идентификатор: объект на руках — доказательство того,
 * что доступ к ней есть, идентификатор доказательством не является. Хранится от неё только
 * идентификатор — состав за время жизни приглашения устареет, а при вступлении читается заново.
 *
 * Помнит выдавшего, и это не справка: вступление читает аптечку **его** правами, потому что
 * приглашённого в ней ещё нет. Отсюда следствие, которое стоит знать: пригласивший вышел —
 * приглашение перестало работать. Оно выдано на его правах, а не само по себе.
 */
class Invitation(medKit: MedKit, val invitedBy: UUID) {
    val medKitId: UUID = medKit.id
}
