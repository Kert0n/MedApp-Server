package org.kert0n.medappserver.domain

import java.util.UUID

/**
 * Выданное приглашение в аптечку.
 *
 * Несёт не только аптечку, но и того, кто приглашение выдал, и это не справка: вступление
 * читает аптечку **его** правами. Приглашённого в ней ещё нет, а читать то, к чему доступа
 * нет, нельзя — иначе во вступлении пришлось бы держать нескоупленное чтение, единственное на
 * всё приложение.
 *
 * Отсюда следствие, которое стоит знать: пригласивший вышел из аптечки — приглашение
 * перестало работать. Оно выдано на его правах, а не само по себе.
 */
data class Invitation(val medKitId: UUID, val invitedBy: UUID)
